"""Compiler contracts for stable Quest Lab ↔ Geo Lab world-object bindings."""
import json
import math
from pathlib import Path
import sys
import unittest

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/"scripts"))
from convert_questlab import compile_questlab, _geo_object_anchor, INTERACTION_CLEARANCE_M

ORIGIN=json.loads((ROOT/"godot/world_data.json").read_text(encoding="utf-8"))["metadata"]
QUEST=json.loads((ROOT/"data/questlab_interactions_demo.json").read_text(encoding="utf-8"))


def synthetic_layout():
    return {
        "metadata":{"projection":"EPSG:32640","origin_lon":ORIGIN["center_lon"],
                    "origin_lat":ORIGIN["center_lat"]},
        "features":[
            {"id":"house-1","type":"house","geometry_type":"Polygon",
             "name":"Дом у дороги","points":[[10,10],[14,10],[14,14],[10,14]]},
            {"id":"car-1","type":"car","geometry_type":"Point",
             "name":"","points":[[25,11]]},
            {"id":"path-1","type":"path","geometry_type":"LineString",
             "name":"","points":[[0,0],[0,6],[0,10]]}
        ]
    }


class GeoQuestBindingTest(unittest.TestCase):
    def test_stale_quest_coordinates_are_replaced_by_authoritative_house_id(self):
        doc=json.loads(json.dumps(QUEST))
        step=doc["quests"][0]["steps"][0]
        step["objectId"]="house-1"
        step["target"]={"lon":55.95,"lat":54.84}
        geo=synthetic_layout()
        before=json.dumps(geo,sort_keys=True)
        result=compile_questlab(doc,ORIGIN,geo)
        first=result["quests"][0]["steps"][0]
        self.assertEqual(first["object_id"],"house-1")
        self.assertEqual(first["object_type"],"house")
        self.assertEqual(first["object_name"],"Дом у дороги")
        self.assertEqual(first["target_source"],"geo_lab_id")
        self.assertEqual(first["target_world"],
                         _geo_object_anchor(geo["features"][0],result["quests"][0]["spawn_world"]))
        self.assertLess(abs(first["target_world"][0]),200)
        self.assertLess(abs(first["target_world"][2]),200)
        self.assertEqual(json.dumps(geo,sort_keys=True),before)
        self.assertEqual(first,compile_questlab(doc,ORIGIN,geo)["quests"][0]["steps"][0])

    def test_house_marker_is_outside_solid_building_in_world_metres(self):
        house=synthetic_layout()["features"][0]
        for spawn in [[0,0,0],[12,0,-30],[30,0,-12]]:
            x,_,z=_geo_object_anchor(house,spawn)
            y=-z
            self.assertFalse(10<x<14 and 10<y<14,
                             "An inaccessible centre is not a valid interaction location")
            self.assertGreaterEqual(math.dist((x,y),(12,12)),2.0)
            self.assertGreater(INTERACTION_CLEARANCE_M,1.0)

    def test_survey_point_and_line_are_resolved_in_local_world(self):
        features=synthetic_layout()["features"]
        self.assertEqual(_geo_object_anchor(features[1],[0,0,0]),[25,0.22,-11])
        self.assertEqual(_geo_object_anchor(features[2],[0,0,0]),[0.0,0.22,-5.0])

    def test_missing_link_is_a_build_error_not_a_silent_fallback(self):
        doc=json.loads(json.dumps(QUEST))
        with self.assertRaisesRegex(ValueError,"not found"):
            compile_questlab(doc,ORIGIN,synthetic_layout())
        bad=synthetic_layout()
        bad["metadata"]["origin_lon"]+=0.001
        with self.assertRaisesRegex(ValueError,"origin mismatch"):
            compile_questlab(doc,ORIGIN,bad)
        bad=synthetic_layout()
        bad["features"].append(dict(bad["features"][0]))
        with self.assertRaisesRegex(ValueError,"Duplicate"):
            compile_questlab(doc,ORIGIN,bad)

    def test_authored_main_quest_remains_backward_compatible(self):
        old=json.loads((ROOT/"data/questlab_return_cordon.json").read_text(encoding="utf-8"))
        plain=compile_questlab(old,ORIGIN)
        linked=compile_questlab(old,ORIGIN,synthetic_layout())
        self.assertEqual(plain,linked)
        self.assertTrue(all(step["target_source"]=="free_point"
                            for step in linked["quests"][0]["steps"]))

    def test_real_surveyed_house_is_used_when_local_layout_exists(self):
        f=ROOT/"godot/manual_layout.json"
        if not f.exists():
            self.skipTest("Conversion artefact is generated by CI before this test")
        layout=json.loads(f.read_text(encoding="utf-8"))
        doc=json.loads(json.dumps(QUEST))
        compiled=compile_questlab(doc,ORIGIN,layout)
        step=compiled["quests"][0]["steps"][0]
        self.assertEqual(step["object_id"],"4499fe7a-c031-469c-aac4-96636c23eea8")
        self.assertEqual(step["object_type"],"house")
        self.assertEqual(step["target_source"],"geo_lab_id")
        old_lon=doc["quests"][0]["steps"][0]["target"]["lon"]
        self.assertNotEqual(step["target_world"],[
            old_lon,0.22,doc["quests"][0]["steps"][0]["target"]["lat"]])
        self.assertEqual(compiled["quests"][0]["steps"][1]["target_source"],"free_point")


if __name__=="__main__":
    unittest.main()
